export const shoppingLists = pgTable("shopping_lists", {
  id: uuid("id").primaryKey().defaultRandom(),
  userId: uuid("user_id").notNull().references(() => users.id, { onDelete: "cascade" }),
  name: text("name").notNull().default("Shopping list"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

export const shoppingListItems = pgTable(
  "shopping_list_items",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    listId: uuid("list_id").notNull().references(() => shoppingLists.id, { onDelete: "cascade" }),
    canonicalItem: text("canonical_item").notNull(),
    displayName: text("display_name").notNull(),
    /** Summed across every recipe on the list, per unit. */
    quantity: real("quantity"),
    unit: text("unit"),
    /** Which recipes contributed this line, so the user can see why it's here. */
    recipeIds: uuid("recipe_ids").array().notNull().default([]),
    checked: boolean("checked").notNull().default(false),
  },
  (t) => [
    index("shopping_list_items_list_idx").on(t.listId),
    // One line per ingredient per list — merging is the whole point, so a
    // second add of the same item must update rather than duplicate.
    uniqueIndex("shopping_list_items_item_idx").on(t.listId, t.canonicalItem),
  ],
);

/**
 * A shopper's link to a grocery service they've signed in to.
 *
 * Only Kroger needs one today: its Cart API writes to a *customer's* cart, so
 * it takes an OAuth token belonging to that person, and it prices and stocks
 * per store, so the chosen location lives here too.
 *
 * The access and refresh tokens are live grocery-account credentials, so they
 * are encrypted with an application key (`GROCERY_TOKEN_ENCRYPTION_KEY`) before
 * they are written and decrypted on read — see `crypto.ts`. Storage-at-rest
 * encryption alone wouldn't help against a leaked backup or a stray read; the
 * key lives in the environment, not the database. Values carry an `enc:v1:`
 * tag, so a pre-encryption row still reads until the backfill converts it.
 */
export const groceryConnections = pgTable(
  "grocery_connections",
  {
    userId: uuid("user_id").notNull().references(() => users.id, { onDelete: "cascade" }),
    provider: text("provider").notNull(),
    accessToken: text("access_token").notNull(),
    refreshToken: text("refresh_token"),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    /** Kroger prices, stocks, and carries different things per store. */
    locationId: text("location_id"),
    locationName: text("location_name"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [primaryKey({ columns: [t.userId, t.provider] })],
);

/**
 * Record of pushing a list to a grocery or delivery service. Instacart and
 * Kroger have real cart APIs; the rest are deep links, and we keep the same
 * row shape for both so the history reads consistently.
 */
export const cartHandoffs = pgTable(
  "cart_handoffs",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    listId: uuid("list_id").notNull().references(() => shoppingLists.id, { onDelete: "cascade" }),
    provider: text("provider").notNull(),
    /** The URL we sent the user to — a provider cart page or a search deep link. */
    handoffUrl: text("handoff_url").notNull(),
    /** Items we could not map to the provider's catalogue. */
    unmatchedItems: text("unmatched_items").array().notNull().default([]),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("cart_handoffs_list_idx").on(t.listId)],
);

// ---------------------------------------------------------------- meal templates

/**
 * A named, reusable meal — a main plus whichever side, drink, and dessert go
 * with it. Built from the same picks a "full meal" nutrition total already
 * uses; saving one just gives that combination a name and, optionally, a
 * link to hand someone else.
 */
export const mealTemplates = pgTable("meal_templates", {
  id: uuid("id").primaryKey().defaultRandom(),
  ownerId: uuid("owner_id").notNull().references(() => users.id, { onDelete: "cascade" }),
  name: text("name").notNull(),
  visibility: visibility("visibility").notNull().default("private"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

export const templateRole = pgEnum("template_role", ["main", "side", "drink", "dessert"]);

/**
 * One recipe per role per template — at most one main, one side, one drink,
 * one dessert, the same shape the full-meal total already assumes.
 */
export const mealTemplateItems = pgTable(
  "meal_template_items",
  {
    templateId: uuid("template_id").notNull().references(() => mealTemplates.id, { onDelete: "cascade" }),
    role: templateRole("role").notNull(),
    recipeId: uuid("recipe_id").notNull().references(() => recipes.id, { onDelete: "cascade" }),
  },
  (t) => [primaryKey({ columns: [t.templateId, t.role] })],
);

// ---------------------------------------------------------------- relations

export const usersRelations = relations(users, ({ many }) => ({
  recipes: many(recipes),
  shelves: many(shelves),
  ratings: many(ratings),
  pantryItems: many(pantryItems),
}));

export const recipesRelations = relations(recipes, ({ one, many }) => ({
  owner: one(users, { fields: [recipes.ownerId], references: [users.id] }),
  ingredientIndex: many(recipeIngredients),
  shelfEntries: many(shelfRecipes),
  ratings: many(ratings),
}));

export const shelvesRelations = relations(shelves, ({ one, many }) => ({
  user: one(users, { fields: [shelves.userId], references: [users.id] }),
  entries: many(shelfRecipes),
}));

export const shelfRecipesRelations = relations(shelfRecipes, ({ one }) => ({
  shelf: one(shelves, { fields: [shelfRecipes.shelfId], references: [shelves.id] }),
  recipe: one(recipes, { fields: [shelfRecipes.recipeId], references: [recipes.id] }),
}));

export const recipeIngredientsRelations = relations(recipeIngredients, ({ one }) => ({
  recipe: one(recipes, { fields: [recipeIngredients.recipeId], references: [recipes.id] }),
}));
